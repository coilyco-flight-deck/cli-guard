const fixture = `wrap ward-kdl ops forgejo {
	spec forgejo.swagger.v1.json
	base-url "forgejo.coilysiren.me/api/v1"
	auth header-token { header Authorization; prefix "token "; value ssm "/forgejo/api-token" }
	can read repos { op "repoGet" }
	can create repos { op "createCurrentUserRepo" }
	can delete repos { op "repoDelete" }
}`

func TestRenderProducesValidGo(t *testing.T) {
	gf, err := guardfile.Parse([]byte(fixture))
	if err != nil {
		t.Fatalf("parse fixture: %v", err)
	}
	out, err := Render(gf, "forgejo.guardfile.kdl")
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	// gofmt'd output must parse as a Go file.
	if _, err := parser.ParseFile(token.NewFileSet(), "main.go", out, parser.AllErrors); err != nil {
		t.Fatalf("generated source does not parse: %v\n%s", err, out)
	}
	src := string(out)
	for _, want := range []string{
		"// Code generated by kdl-specs; DO NOT EDIT.",
		"//go:embed forgejo.guardfile.kdl",
		"//go:embed forgejo.swagger.lock.json",
		"var embeddedSpec0 []byte",
		`Name: "ward-kdl"`,
		"specverb.Mount(app",
		`"https://forgejo.coilysiren.me/swagger.v1.json", "WARD_KDL_OPS_FORGEJO_SPEC"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated source missing %q", want)
		}
	}
}

func TestRenderSetMergesIntoOneBinary(t *testing.T) {
	const awsFixture = `wrap ward-kdl ops aws {
		spec aws.swagger.v1.json
		base-url "aws.example.com/api/v1"
		auth header-token { header Authorization; prefix "token "; value ssm "/aws/api-token" }
		can list buckets { op "ListBuckets" }
	}`
	fj, err := guardfile.Parse([]byte(fixture))
	if err != nil {
		t.Fatalf("parse forgejo fixture: %v", err)
	}
	aws, err := guardfile.Parse([]byte(awsFixture))
	if err != nil {
		t.Fatalf("parse aws fixture: %v", err)
	}
	out, err := RenderSet(
		[]*guardfile.Guardfile{fj, aws},
		[]string{"forgejo.guardfile.kdl", "aws.guardfile.kdl"},
	)
	if err != nil {
		t.Fatalf("RenderSet: %v", err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "main.go", out, parser.AllErrors); err != nil {
		t.Fatalf("merged source does not parse: %v\n%s", err, out)
	}
	src := string(out)
	for _, want := range []string{
		"//go:embed forgejo.guardfile.kdl",
		"//go:embed aws.guardfile.kdl",
		"var embeddedGuardfile0 []byte",
		"var embeddedGuardfile1 []byte",
		`"WARD_KDL_OPS_FORGEJO_SPEC"`,
		`"WARD_KDL_OPS_AWS_SPEC"`,
		`Name: "ward-kdl"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("merged source missing %q", want)
		}
	}
}

func TestRenderParamsExecOnly(t *testing.T) {
	out, err := RenderParams(SetParams{
		Binary:  "ward-kdl",
		HasExec: true,
		Mounts:  []Params{{Transport: TransportExec, Binary: "ward-kdl", GuardfileName: "aws.guardfile.kdl"}},
	})
	if err != nil {
		t.Fatalf("RenderParams: %v", err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "main.go", out, parser.AllErrors); err != nil {
		t.Fatalf("exec-only source does not parse: %v\n%s", err, out)
	}
	src := string(out)
	for _, want := range []string{"//go:embed aws.guardfile.kdl", "execverb.Mount(app", "cli/execverb"} {
		if !strings.Contains(src, want) {
			t.Errorf("exec-only source missing %q", want)
		}
	}
	// An exec-only binary must not pull in any spec-only seam, or Go rejects the
	// unused import.
	for _, absent := range []string{"specverb.Mount", "http/specverb", "ssmTokenResolver", "net/http", "embeddedSpec0"} {
		if strings.Contains(src, absent) {
			t.Errorf("exec-only source should not contain spec-only %q", absent)
		}
	}
}

func TestRenderParamsMixed(t *testing.T) {
	out, err := RenderParams(SetParams{
		Binary:  "ward-kdl",
		HasSpec: true,
		HasExec: true,
		Mounts: []Params{
			{Transport: TransportSpec, Binary: "ward-kdl", GuardfileName: "forgejo.guardfile.kdl", SpecLockName: "forgejo.swagger.lock.json", SpecURL: "https://forgejo.coilysiren.me/swagger.v1.json", SpecEnvVar: "WARD_KDL_OPS_FORGEJO_SPEC", Providers: []string{"ssm"}},
			{Transport: TransportExec, Binary: "ward-kdl", GuardfileName: "aws.guardfile.kdl"},
		},
	})
	if err != nil {
		t.Fatalf("RenderParams: %v", err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "main.go", out, parser.AllErrors); err != nil {
		t.Fatalf("mixed source does not parse: %v\n%s", err, out)
	}
	src := string(out)
	for _, want := range []string{
		"specverb.Mount(app", "execverb.Mount(app",
		"//go:embed forgejo.swagger.lock.json", "//go:embed aws.guardfile.kdl", "ssmTokenResolver",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("mixed source missing %q", want)
		}
	}
	// The spec member (index 0) embeds a spec lock; the exec member (index 1) must not.
	if !strings.Contains(src, "embeddedSpec0") {
		t.Error("spec member (index 0) should have a spec-lock embed")
	}
	if strings.Contains(src, "embeddedSpec1") {
		t.Error("exec member (index 1) should not have a spec-lock embed")
	}
}

